const AMP_RE = /&/g;
const LT_RE = /</g;
const GT_RE = />/g;

/** Escape every HTML-special character. The base case for the sanitizer. */
export function escapeHtml(s) {
  return String(s == null ? '' : s)
    .replace(AMP_RE, '&amp;')
    .replace(LT_RE, '&lt;')
    .replace(GT_RE, '&gt;');
}

/**
 * ALLOW-LIST parser for the bump description: `<b>` and `<u>` are honoured,
 * EVERYTHING else stays literal text.
 *
 * Returns SEGMENTS, not an HTML string, on purpose. BlockPreview.jsx holds a
 * hard rule — no dangerouslySetInnerHTML in that file, all operator text
 * through React text nodes — and returning markup would force that rule to be
 * broken there. Segments let the caller render <strong>/<u> elements around
 * auto-escaped text instead, so hostile input cannot become markup at all
 * rather than merely being filtered.
 *
 * (CodeTab.jsx is the ONE audited exception in the builder: its highlight
 * overlay sets innerHTML from codeFormat.js's highlighters, which escape every
 * source character with escHtml() before wrapping it in <span> tags — the
 * output is escaped text plus a fixed set of class-only spans, and the layer
 * is aria-hidden and pointer-events:none.)
 *
 * Unknown tags, attributes on the allowed tags (`<b onclick=…>`), and unclosed
 * tags are all simply not recognised by the regex, so they fall through as
 * literal characters — the failure mode is "shows the angle brackets", never
 * "executes".
 *
 * MATCHED BY THE RENDERER. funnelRender.js escapes the whole description and
 * then un-escapes exactly `<b>`/`</b>`/`<u>`/`</u>`, so the published page
 * shows the same two tags this canvas parser shows — and nothing else.
 *
 * @returns {Array<{text:string,bold:boolean,underline:boolean}>}
 */
export function parseInlineMarkup(text) {
  const src = String(text == null ? '' : text);
  const out = [];
  let bold = 0;
  let underline = 0;
  let buf = '';
  const flush = () => {
    if (!buf) return;
    out.push({ text: buf, bold: bold > 0, underline: underline > 0 });
    buf = '';
  };
  const re = /<(\/?)([bu])>/gi;
  let last = 0;
  let m;
  while ((m = re.exec(src))) {
    buf += src.slice(last, m.index);
    flush();
    const closing = m[1] === '/';
    const tag = m[2].toLowerCase();
    if (tag === 'b') bold = closing ? Math.max(0, bold - 1) : bold + 1;
    else underline = closing ? Math.max(0, underline - 1) : underline + 1;
    last = m.index + m[0].length;
  }
  buf += src.slice(last);
  flush();
  return out;
}

/**
 * The checkbox headline shown on the canvas.
 *
 * Blank `headline` AUTO-BUILDS from the offer name and the display price —
 * which is the picked variant's live Shopify price, written into props.price
 * by the picker. With no price we say less rather than inventing a number: a
 * headline reading "for ONLY $" would be a claim about money we do not have.
 */
export const BUMP_DEFAULT_HEADLINE = 'Yes! Add this one-time offer to my order';
export const BUMP_DEFAULT_NAME_COLOR = '#111827';

/**
 * MIRRORS THE SERVER EXACTLY. funnelRender.js order_bump:
 *
 *   p.headline  ->  offer_name ? `Yes, I want the ${offer_name}!`
 *               ->  p.label    ->  the default string
 *
 * NOTE WHAT IS ABSENT: the server's auto-headline carries NO PRICE. An earlier
 * draft of this function built "…for ONLY $19" from props.price, which would
 * have made the canvas advertise a number the published page never prints —
 * a preview that lies about money. The precedence and the wording here are
 * copied from the renderer, not invented, and the harness pins them.
 */
export function bumpHeadline(props) {
  // NOT a destructuring default: `= {}` only fires for `undefined`, and the
  // caller passes `block.props`, which is legally null on a block the API
  // accepted. Destructuring null throws.
  const p = props && typeof props === 'object' ? props : {};
  const headline = typeof p.headline === 'string' ? p.headline.trim() : '';
  if (headline) return headline;
  const name = typeof p.offer_name === 'string' ? p.offer_name.trim() : '';
  if (name) return `Yes, I want the ${name}!`;
  const label = typeof p.label === 'string' ? p.label.trim() : '';
  if (label) return label;
  return BUMP_DEFAULT_HEADLINE;
}

/**
 * The offer-name colour the server will actually use: a STRICT hex, or its
 * default ink. The renderer tests `^#[0-9a-fA-F]{3,8}$` and silently falls
 * back — so the canvas must fall back on exactly the same inputs, or an
 * operator typing `red` sees red here and near-black on the live page.
 */
export function bumpNameColor(props) {
  const p = props && typeof props === 'object' ? props : {};
  const raw = String(p.offer_name_color == null ? '' : p.offer_name_color);
  return /^#[0-9a-fA-F]{3,8}$/.test(raw) ? raw : BUMP_DEFAULT_NAME_COLOR;
}

/**
 * F15. A price is only a price when it names an AMOUNT. `0`, `'0'`, `'$0.00'`,
 * `''` and null all mean "no price to advertise". Used for the canvas's
 * secondary "from …" line, which is builder chrome — the server prints
 * props.price verbatim when it is non-blank.
 */
export function displayPrice(price) {
  if (price == null) return '';
  const s = String(price).trim();
  if (!s) return '';
  // Strip currency symbols/separators to ask "is this numerically zero?"
  const numeric = s.replace(/[^0-9.-]/g, '');
  if (numeric && Number(numeric) === 0) return '';
  return s;
}

/**
 * True when the bump has no product wired — the state the canvas must call
 * out, and the state the server refuses with 422 bump_not_chargeable.
 */
export function bumpUnconfigured(props) {
  const p = props && typeof props === 'object' ? props : {};
  // F14. `||` not `??`, matching the server EXACTLY: checkoutPublic does
  // `String(bp.variant_id || '').trim()`, so variant_id = 0 / '' / false is
  // unwired THERE. `??` would call 0 configured here and the canvas would
  // promise a charge the server refuses with 422 bump_not_chargeable.
  return !String(p.variant_id || '').trim();
}

/**
 * The server refuses a duplicate page slug with 409 "A page with this slug
 * already exists in this funnel" (routes/funnels.js). Detecting it lets the
 * panel put the refusal NEXT TO THE FIELD THAT CAUSED IT instead of leaving
 * the operator to connect a top-bar banner to a box three sections away.
 *
 * Matched on the message rather than the status because the save engine
 * surfaces `err.response.data.error` — a string — and never the code.
 */
export function isSlugCollision(saveError) {
  // F16. Scoped to the PAGE refusal. The funnel-level message
  // ("A funnel with this slug already exists") is a different field on a
  // different screen — matching it would point the operator at the page slug
  // box for a problem that is not there.
  return /A page with this slug already exists/i.test(String(saveError == null ? '' : saveError));
}

/**
 * `data-blk-name` hook value. Empty (→ attribute omitted) unless the operator
 * named the block, so an unnamed block emits no attribute at all.
 */
export function blockNameAttr(props) {
  const p = props && typeof props === 'object' ? props : {};
  const name = typeof p.block_name === 'string' ? p.block_name.trim() : '';
  return name;
}

/**
 * Which DIRTY FIELD a save refusal names, or null when the refusal is not
 * about one field in particular.
 *
 * The save engine sends every dirty field in ONE PATCH. When the server
 * refuses, re-dirtying the whole set means the offending field rides along on
 * every later save too — one slug collision then refuses the operator's next
 * hour of block edits. Naming the field lets the engine hold back that one and
 * let the rest through.
 *
 * Message-matched, not status-matched, for the same reason isSlugCollision is:
 * the engine only ever sees `err.response.data.error`, a string.
 */
export function refusedSaveField(saveError) {
  if (isSlugCollision(saveError)) return 'slug';
  return null;
}

/**
 * The fields a refused PATCH should leave DIRTY, so the next flush resends
 * them. Everything the request carried, minus the one field the refusal names.
 *
 * Dropping only the named field is the point: a rejected save must never
 * silently lose an edit, but re-queueing the field the server just refused
 * guarantees the NEXT save is refused too, and the one after that. One taken
 * slug used to wedge every later write on the page.
 *
 * Total — `keys` is whatever the caller had in its dirty set.
 */
export function retryFieldsAfterRefusal(keys, saveError) {
  const refused = refusedSaveField(saveError);
  const list = Array.isArray(keys) ? keys : [];
  return list.filter((k) => k !== refused);
}

/** The meta fields the top bar and the inspector render. */
export const META_FIELDS = Object.freeze(['title', 'slug', 'status']);

/** The meta bag a page row describes. Same coercions load() and restore use. */
export function metaFromPage(page) {
  const p = page && typeof page === 'object' ? page : {};
  return { title: p.title || '', slug: p.slug || '/', status: p.status || 'draft' };
}

/**
 * Meta re-synced from a successful PATCH response.
 *
 * THE PHANTOM-SLUG FIX. retryFieldsAfterRefusal drops a refused field from the
 * dirty set so one taken slug cannot poison every later save — but the refused
 * VALUE stayed in `meta`, which is what the slug box renders. The box then
 * showed a value that existed nowhere but this browser, and the next
 * successful save of anything else cleared the error banner, leaving the chip
 * reading "Saved" over a slug the server had never accepted.
 *
 * `dirtyFields` is the set still queued when the response lands. Those belong
 * to the OPERATOR — they were typed after this PATCH went out — and are
 * skipped, which is what stops the re-sync from eating keystrokes.
 *
 * Returns `current` unchanged when nothing moved, so React can bail out.
 */
export function resyncMeta(current, page, dirtyFields) {
  const cur = current && typeof current === 'object' ? current : {};
  // No page in the response is not authority to overwrite anything.
  if (!page || typeof page !== 'object') return cur;
  const server = metaFromPage(page);
  const dirty = dirtyFields instanceof Set
    ? dirtyFields
    : new Set(Array.isArray(dirtyFields) ? dirtyFields : []);
  let changed = false;
  const next = { ...cur };
  for (const k of META_FIELDS) {
    if (dirty.has(k)) continue;
    if (next[k] !== server[k]) { next[k] = server[k]; changed = true; }
  }
  return changed ? next : cur;
}

/**
 * Sticky per-field refusals: { slug: { message, value } }.
 *
 * The top-bar banner rides on `saveError`, which the next successful save
 * clears. A refusal whose field is no longer queued would therefore vanish
 * from the screen while its cause was still unresolved — so it is recorded
 * against the FIELD, with the value that was rejected, and cleared only when a
 * write actually carries that field (or a restore replaces the page).
 */
export function recordRefusal(refusals, saveError, payload) {
  const base = refusals && typeof refusals === 'object' ? refusals : {};
  const field = refusedSaveField(saveError);
  if (!field) return base;
  const p = payload && typeof payload === 'object' ? payload : {};
  return { ...base, [field]: { message: String(saveError), value: p[field] } };
}

/** Drops refusals for fields a write has now carried. Identity when no match. */
export function clearRefusals(refusals, fields) {
  const base = refusals && typeof refusals === 'object' ? refusals : {};
  const list = Array.isArray(fields) ? fields : [];
  if (!list.some((k) => Object.prototype.hasOwnProperty.call(base, k))) return base;
  const next = { ...base };
  for (const k of list) delete next[k];
  return next;
}

// ---------------------------------------------------------------------------
// Structured list fields — FAQ / Ranking / Comparison / Product grid
//
// These four blocks are LIST-SHAPED: their content prop is an array of row
// objects the server renderer walks. Every helper below is TOTAL, for the
// usual reason — the array is operator/AI-authored JSON and can legally hold
// a null, a string, or a nested array.
//
// FILTERING IS DELIBERATE AND MIRRORS THE RENDERER. funnelRender.js does
// `.filter(isPlainObject)` on ranking.items, faq.items, comparison_table.rows
// and product_grid.items — a non-object row is ALREADY invisible on the public
// page. Showing it in the editor would be the panel promising to edit
// something the page will never print, so `listRows` drops it on read and the
// first edit normalizes it away.
// ---------------------------------------------------------------------------

/** A plain object — not null, not an array. Same test the renderer applies. */
function isRowObject(v) {
  return !!v && typeof v === 'object' && !Array.isArray(v);
}

/**
 * The rows a list-shaped prop actually renders as: plain objects only.
 * Anything else (null, string, nested array) is dropped, exactly as
 * funnelRender.js drops it.
 *
 * RETURNS THE INPUT ARRAY UNCHANGED when there is nothing to drop, and that
 * identity is load-bearing rather than an optimization. Every mutation helper
 * below returns `listRows(rows)` on a no-op path, and RowsField writes only
 * when the result is a DIFFERENT array — so `↑` on the first row, a remove
 * past the end, or a refused column rename must come back as the very same
 * array or the panel would push an identical props value through commit() and
 * bank an undo step that undoes nothing.
 */
export function listRows(value) {
  if (!Array.isArray(value)) return [];
  return value.every(isRowObject) ? value : value.filter(isRowObject);
}

/** Append a row. `defaultRow` is shallow-copied so the registry's literal is never shared. */
export function addListRow(rows, defaultRow) {
  return [...listRows(rows), isRowObject(defaultRow) ? { ...defaultRow } : {}];
}

/**
 * Drop row `index`. An out-of-range index returns the SAME array identity, so
 * the caller can skip the write and no empty history entry is recorded.
 */
export function removeListRow(rows, index) {
  const list = listRows(rows);
  if (!Number.isInteger(index) || index < 0 || index >= list.length) return list;
  return list.filter((_, i) => i !== index);
}

/**
 * Move row `index` by `delta` (-1 up, +1 down). A move that would leave the
 * array returns the SAME array identity — that is what makes the ↑ on the
 * first row a no-op rather than a silent reorder or a crash.
 */
export function moveListRow(rows, index, delta) {
  const list = listRows(rows);
  const to = index + delta;
  if (!Number.isInteger(index) || !Number.isInteger(delta) || delta === 0) return list;
  if (index < 0 || index >= list.length || to < 0 || to >= list.length) return list;
  const next = list.slice();
  const [moved] = next.splice(index, 1);
  next.splice(to, 0, moved);
  return next;
}

/**
 * Write one cell.
 *
 * `undefined` DELETES the key; an empty STRING is kept. The difference is
 * load-bearing for comparison tables: the renderer derives the column set from
 * `Object.keys(rows[0])`, so letting a cleared text cell delete its key would
 * make emptying the first row's cell delete the whole COLUMN from the page.
 */
export function setListCell(rows, index, key, value) {
  const list = listRows(rows);
  if (!Number.isInteger(index) || index < 0 || index >= list.length) return list;
  if (typeof key !== 'string' || !key) return list;
  return list.map((row, i) => {
    if (i !== index) return row;
    const next = { ...row };
    if (value === undefined) delete next[key];
    else next[key] = value;
    return next;
  });
}

// ---------------------------------------------------------------------------
// Comparison table columns
//
// MIRRORS THE RENDERER EXACTLY. funnelRender.js comparison_table reads
//   const cols = Object.keys(rows[0]).filter((k) => k !== 'feature');
// — the FIRST row alone decides the columns, and every later row is read as
// `r[c] ?? ''`. So a key present only on row 3 is invisible on the page, and
// the editor must not draw a cell for it. Every mutation below therefore
// applies to EVERY row, which is what keeps row 0 (the header source) and the
// body in agreement.
// ---------------------------------------------------------------------------

/** The column names the published page will print, in the order it prints them. */
export function comparisonColumns(rows) {
  const list = listRows(rows);
  if (!list.length) return [];
  return Object.keys(list[0]).filter((k) => k !== 'feature');
}

/** Refuse blank names, the reserved `feature` key, and duplicates. */
function columnNameUsable(rows, name) {
  const n = typeof name === 'string' ? name.trim() : '';
  if (!n || n === 'feature') return null;
  if (comparisonColumns(rows).includes(n)) return null;
  return n;
}

/** Append a column to EVERY row (empty cell). Identity when the name is unusable. */
export function addComparisonColumn(rows, name) {
  const list = listRows(rows);
  const n = columnNameUsable(list, name);
  if (!n) return list;
  return list.map((r) => ({ ...r, [n]: '' }));
}

/**
 * Rename a column IN PLACE on every row — key order is rebuilt rather than
 * patched, because `{...r, [to]: v}` after a delete would move the column to
 * the END and silently reorder the published table's headers.
 */
export function renameComparisonColumn(rows, from, to) {
  const list = listRows(rows);
  if (typeof from !== 'string' || !comparisonColumns(list).includes(from)) return list;
  const n = columnNameUsable(list, to);
  if (!n || n === from) return list;
  return list.map((r) => {
    const next = {};
    for (const k of Object.keys(r)) {
      if (k === from) next[n] = r[k];
      else next[k] = r[k];
    }
    return next;
  });
}

/** Drop a column from every row. Identity when the column is not present. */
export function removeComparisonColumn(rows, name) {
  const list = listRows(rows);
  if (typeof name !== 'string' || !comparisonColumns(list).includes(name)) return list;
  return list.map((r) => {
    const next = { ...r };
    delete next[name];
    return next;
  });
}

/**
 * The row a comparison table's "Add row" must insert: `feature` plus one EMPTY
 * cell per CURRENT column. A row that skipped the columns would render as a
 * line of blanks and — if it ever became row 0 — would delete every column
 * from the page.
 */
export function comparisonDefaultRow(rows, feature) {
  const out = { feature: typeof feature === 'string' ? feature : 'New feature' };
  for (const c of comparisonColumns(rows)) out[c] = '';
  return out;
}

// ---------------------------------------------------------------------------
// Countdown deadline
//
// The renderer emits the deadline as an ATTRIBUTE (`data-deadline`, esc()'d)
// and its runtime reads it with getAttribute + Date.parse. The value is never
// spliced into the emitted JS, so no backtick/${}/backslash constraint applies
// to it — but it MUST be something Date.parse understands, which is why the
// panel stores a full ISO instant rather than the browser's zone-less
// `datetime-local` string.
// ---------------------------------------------------------------------------

/**
 * `datetime-local` value (`2026-12-31T23:59`, no zone → LOCAL time) → ISO
 * instant. Blank or unparseable returns '' so the caller deletes the prop
 * instead of writing a deadline the runtime would ignore.
 */
export function isoFromLocalInput(value) {
  const raw = typeof value === 'string' ? value.trim() : '';
  if (!raw) return '';
  const ms = Date.parse(raw);
  if (!Number.isFinite(ms)) return '';
  return new Date(ms).toISOString();
}

/**
 * ISO instant → the `datetime-local` string the input renders, in the
 * operator's LOCAL zone (which is the zone they typed it in). Unparseable
 * returns '' — an invalid deadline shows as an empty picker, and the raw value
 * is surfaced next to it rather than silently rewritten.
 */
export function localInputFromIso(value) {
  const raw = typeof value === 'string' ? value.trim() : '';
  if (!raw) return '';
  const ms = Date.parse(raw);
  if (!Number.isFinite(ms)) return '';
  const d = new Date(ms);
  const p = (n) => (n < 10 ? '0' : '') + n;
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}T${p(d.getHours())}:${p(d.getMinutes())}`;
}

/**
 * What the countdown clock reads, for the canvas preview.
 *
 * MIRRORS countdownRuntimeScript() IN funnelRender.js CHARACTER FOR CHARACTER:
 * `Date.parse` for the deadline, `(d>0?d+'d ':'')+pad(h)+':'+pad(m)+':'+pad(s)`
 * for the clock, and the literal 'Offer expired' once the instant is past. A
 * preview that formatted it differently would be a preview of a page that does
 * not exist — which is exactly what the old hard-coded `23:59:59` was.
 *
 * `state` lets the canvas distinguish the three NON-TICKING cases the runtime
 * treats as one silent no-op: no deadline, an unparseable deadline, and a real
 * expiry. Only the last one is the block working as intended.
 *
 * @returns {{state:'unset'|'invalid'|'expired'|'live', text:string}}
 */
export function countdownPreview(deadline, nowMs) {
  const raw = deadline == null ? '' : String(deadline).trim();
  if (!raw) return { state: 'unset', text: '—' };
  const end = Date.parse(raw);
  if (!Number.isFinite(end)) return { state: 'invalid', text: '—' };
  const now = Number.isFinite(nowMs) ? nowMs : Date.now();
  const ms = end - now;
  if (ms <= 0) return { state: 'expired', text: 'Offer expired' };
  const total = Math.floor(ms / 1000);
  const d = Math.floor(total / 86400);
  const h = Math.floor((total % 86400) / 3600);
  const m = Math.floor((total % 3600) / 60);
  const s = total % 60;
  const pad = (n) => (n < 10 ? '0' : '') + n;
  return { state: 'live', text: `${d > 0 ? `${d}d ` : ''}${pad(h)}:${pad(m)}:${pad(s)}` };
}

