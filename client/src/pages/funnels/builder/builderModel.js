// PAGE BUILDER — pure model helpers for the Outline tab and the Code tab.
//
// Dependency-free ON PURPOSE (no JSX, no lucide, no blockRegistry import) so
// node can exercise them directly — see server/tests/builder/builder-model.mjs.
// Anything registry-shaped (labels, icons) is INJECTED by the caller rather
// than imported, which is also what keeps these functions total: they are fed
// whatever the server had in `blocks`, including rows that predate any schema.
//
// TOTALITY IS THE POINT. `blocks` is operator/AI-authored JSON that has only
// ever been validated for `type: string` + `props: object` (funnels.js
// validateBlocks) — it can legally contain a `row` whose `columns` is a
// string, a block with no id, or a null in the array. None of that may throw
// inside a render pass, so every function here drops what it cannot read.

// ---------------------------------------------------------------------------
// Outline
// ---------------------------------------------------------------------------

/** Fallback label when the caller injects no labelFor. */
export function defaultLabel(block) {
  const name = block && block.props && typeof block.props === 'object' ? block.props.block_name : null;
  if (typeof name === 'string' && name.trim()) return name.trim();
  const type = block && typeof block.type === 'string' ? block.type : '';
  return type || 'Unknown';
}

/**
 * Flatten `blocks` into outline rows.
 *
 * Every TOP-LEVEL row carries `index` — the position in the blocks array,
 * which is what reorder/move operate on. Child rows (a `row` block's columns)
 * are presentation only: they are NOT independently movable, so they carry
 * `movable:false` and their `index` points at the PARENT. A drag handler that
 * reads `index` off a child therefore reorders the parent rather than
 * corrupting the array with a column index.
 *
 * @param {unknown} blocks   the raw blocks array
 * @param {(b:object)=>string} [labelFor]  registry-aware label resolver
 * @returns {Array<{key:string,id:string|null,index:number,type:string,label:string,depth:number,movable:boolean,parentId:string|null}>}
 */
export function buildOutline(blocks, labelFor) {
  const label = typeof labelFor === 'function' ? labelFor : defaultLabel;
  const rows = [];
  const list = Array.isArray(blocks) ? blocks : [];
  // F17. Ids are supposed to be unique, but `blocks` is operator/AI-authored
  // and a duplicated id is reachable (a hand-edited paste, an AI insert_block
  // echoing an existing id). Two React children with the same key silently
  // drop one row, so the key is disambiguated by position — the DISPLAY stays
  // honest even when the data is not.
  const keyCount = new Map();
  const uniqueKey = (base) => {
    const n = keyCount.get(base) || 0;
    keyCount.set(base, n + 1);
    return n === 0 ? base : `${base}__dup${n}`;
  };
  for (let index = 0; index < list.length; index += 1) {
    const b = list[index];
    // A null/primitive entry cannot be selected or labelled — skipping it
    // keeps the outline honest rather than rendering a ghost row.
    if (!b || typeof b !== 'object' || Array.isArray(b)) continue;
    const type = typeof b.type === 'string' && b.type ? b.type : 'unknown';
    const id = typeof b.id === 'string' && b.id ? b.id : null;
    rows.push({
      key: uniqueKey(id || `idx_${index}`),
      id,
      index,
      type,
      label: String(label(b) ?? '') || type,
      depth: 0,
      movable: true,
      parentId: null,
    });
    // `row` blocks nest columns. Anything else with a columns prop is not a
    // row and must not sprout children.
    if (type !== 'row') continue;
    const props = b.props && typeof b.props === 'object' ? b.props : {};
    const cols = Array.isArray(props.columns) ? props.columns : [];
    for (let c = 0; c < cols.length; c += 1) {
      rows.push({
        key: uniqueKey(`${id || `idx_${index}`}__col${c}`),
        id,
        index,
        type: 'column',
        label: `Column ${c + 1}`,
        depth: 1,
        movable: false,
        parentId: id,
      });
    }
  }
  return rows;
}

